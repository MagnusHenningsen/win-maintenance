Register-Feature @{
    Name    = 'Internet'
    Section = 'fix'
    Order   = 10
    Glyph   = 'E701'
    Title   = 'Internet problems'
    Desc    = "Find out why the internet isn't working, and try a fix."
    Open    = { Start-NetDiagnosis }
    Engine  = {
        # Runs every check in order. A hard failure stops later checks (they're marked "not tested").
        # Ping steps (router, internet) only warn, because many networks block pings; the web test decides.
        function Invoke-NetDiagnosis {
            $keys = 'net.adapter', 'net.ip', 'net.router', 'net.internet', 'net.dns', 'net.web'
            $result = [pscustomobject]@{ Failed = $false; Portal = $false; Verdict = ''; Note = '' }
            $skipFrom = {
                param($i)
                for ($k = $i; $k -lt $keys.Count; $k++) { Step $keys[$k] 'skip' (T 'Not tested') }
            }

            # 1. Network connection
            Step 'net.adapter' 'running'
            SetStatus (T 'Looking for a network connection') 5
            $up = @(Get-NetAdapter -Physical -ErrorAction SilentlyContinue | Where-Object { $_.Status -eq 'Up' })
            if (-not $up.Count) {
                Step 'net.adapter' 'error' (T 'Not connected to any network')
                & $skipFrom 1
                $result.Failed = $true
                $result.Verdict = T "Your PC isn't connected to any network. Turn on Wi-Fi or plug in a network cable."
                return $result
            }
            $wifi = $up | Where-Object { $_.NdisPhysicalMedium -eq 9 -or $_.PhysicalMediaType -match '802\.11' } | Select-Object -First 1
            if ($wifi) {
                $ssid = (Get-NetConnectionProfile -InterfaceIndex $wifi.ifIndex -ErrorAction SilentlyContinue | Select-Object -First 1).Name
                $signal = $null
                $m = [regex]::Match((Get-NativeText netsh @('wlan', 'show', 'interfaces')), '(\d{1,3})\s*%')
                if ($m.Success) { $signal = [int]$m.Groups[1].Value }
                if ($null -eq $signal) { Step 'net.adapter' 'ok' ((T 'Wi-Fi "{0}"') -f $ssid) }
                elseif ($signal -lt 35) {
                    Step 'net.adapter' 'warn' ((T 'Wi-Fi "{0}", weak signal ({1}%)') -f $ssid, $signal)
                    $result.Note = T "Weak Wi-Fi signal: move closer to the router if the connection is slow or drops."
                }
                else { Step 'net.adapter' 'ok' ((T 'Wi-Fi "{0}", signal {1}%') -f $ssid, $signal) }
            } else {
                Step 'net.adapter' 'ok' (T 'Network cable')
            }

            # 2. IP address from the router
            Step 'net.ip' 'running'
            SetStatus (T 'Checking the IP address') 20
            $cfg = @(Get-NetIPConfiguration -ErrorAction SilentlyContinue |
                Where-Object { $_.IPv4DefaultGateway -and $_.NetAdapter -and $_.NetAdapter.Status -eq 'Up' })
            if (-not $cfg.Count) {
                $apipa = @(Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue | Where-Object { $_.IPAddress -like '169.254.*' })
                $txt = if ($apipa.Count) { T "Didn't get an address from the router" } else { T 'No router found' }
                Step 'net.ip' 'error' $txt
                & $skipFrom 2
                $result.Failed = $true
                $result.Verdict = T "Your PC is connected, but didn't get an address from the router. Restarting the router (turn it off, wait 30 seconds, turn it on) often fixes this."
                return $result
            }
            $gw = @($cfg[0].IPv4DefaultGateway)[0].NextHop
            $ip = @($cfg[0].IPv4Address)[0].IPAddress
            Log "Gateway $gw, address $ip" 'detail'
            Step 'net.ip' 'ok' ((T 'Address {0}') -f $ip)

            # 3. Router answers ping (soft)
            Step 'net.router' 'running'
            SetStatus (T 'Contacting the router') 35
            $routerOk = Test-Connection -ComputerName $gw -Count 2 -Quiet -ErrorAction SilentlyContinue
            if ($routerOk) { Step 'net.router' 'ok' (T 'Answers') } else { Step 'net.router' 'warn' (T "Didn't answer (some routers ignore this test)") }

            # 4. Internet answers ping (soft)
            Step 'net.internet' 'running'
            SetStatus (T 'Contacting the internet') 50
            $netOk = (Test-Connection -ComputerName 1.1.1.1 -Count 2 -Quiet -ErrorAction SilentlyContinue) -or
                     (Test-Connection -ComputerName 8.8.8.8 -Count 2 -Quiet -ErrorAction SilentlyContinue)
            if ($netOk) { Step 'net.internet' 'ok' (T 'Reachable') } else { Step 'net.internet' 'warn' (T "Didn't answer (some networks block this test)") }

            # 5. DNS
            Step 'net.dns' 'running'
            SetStatus (T 'Looking up a website name') 65
            $dnsOk = $false
            try { $null = Resolve-DnsName -Name 'www.microsoft.com' -DnsOnly -QuickTimeout -ErrorAction Stop; $dnsOk = $true } catch { Log $_.Exception.Message 'detail' }
            if (-not $dnsOk) {
                Step 'net.dns' 'error' (T "Can't look up website names")
                & $skipFrom 5
                $result.Failed = $true
                $result.Verdict = if ($netOk) { T "The internet works, but your PC can't look up website names (DNS). A quick fix often helps." }
                                  else { T "Your PC is connected, but can't reach the internet. The problem is probably the router or the internet provider." }
                return $result
            }
            Step 'net.dns' 'ok' (T 'Works')

            # 6. A real web request (also detects hotel/guest Wi-Fi sign-in pages)
            Step 'net.web' 'running'
            SetStatus (T 'Loading a test page') 85
            try {
                $resp = Invoke-WebRequest -Uri 'http://www.msftconnecttest.com/connecttest.txt' -UseBasicParsing -TimeoutSec 15 -ErrorAction Stop
                if ("$($resp.Content)".Trim() -eq 'Microsoft Connect Test') {
                    Step 'net.web' 'ok' (T 'Websites load normally')
                    # Pings that failed don't matter when the web works
                    if (-not $routerOk) { Step 'net.router' 'ok' (T 'Fine: websites load, this test is just blocked') }
                    if (-not $netOk) { Step 'net.internet' 'ok' (T 'Fine: websites load, this test is just blocked') }
                    $result.Verdict = T 'Everything checked out. If one website or app still has problems, the problem is probably on their side.'
                } else {
                    Step 'net.web' 'warn' (T 'The network wants you to sign in first')
                    $result.Portal = $true
                    $result.Verdict = T "You're connected, but the network wants you to sign in first. This is common on hotel and guest Wi-Fi. Open the sign-in page to continue."
                }
            } catch {
                Log $_.Exception.Message 'detail'
                Step 'net.web' 'error' (T "Websites don't load")
                $result.Failed = $true
                $result.Verdict = if ($netOk) { T "Your PC is connected, but websites don't load. A firewall, VPN or proxy may be blocking them." }
                                  else { T "Your PC is connected, but can't reach the internet. The problem is probably the router or the internet provider." }
            }
            SetStatus '' 100
            return $result
        }

        function Invoke-NetFix([bool]$Admin) {
            Step 'fix.dns' 'running'
            SetStatus (T 'Clearing the name lookup cache') 10
            $c = Invoke-Native ipconfig @('/flushdns')
            if ($c -eq 0) { Step 'fix.dns' 'ok' (T 'Cleared') } else { Step 'fix.dns' 'warn' ((T 'Failed (code {0})') -f $c) }

            if (-not $Admin) {
                Step 'fix.ip' 'skip' (T 'Needs administrator')
                Step 'fix.adapter' 'skip' (T 'Needs administrator')
                return [pscustomobject]@{ Done = $true }
            }

            Step 'fix.ip' 'running'
            SetStatus (T 'Asking the router for a new address') 30
            $null = Invoke-Native ipconfig @('/release')
            $c = Invoke-Native ipconfig @('/renew')
            if ($c -eq 0) { Step 'fix.ip' 'ok' (T 'Got a new address') } else { Step 'fix.ip' 'warn' ((T 'Failed (code {0})') -f $c) }

            Step 'fix.adapter' 'running'
            SetStatus (T 'Restarting the network adapter') 60
            $ads = @(Get-NetAdapter -Physical -ErrorAction SilentlyContinue | Where-Object { $_.Status -ne 'Disabled' })
            if (-not $ads.Count) { Step 'fix.adapter' 'warn' (T 'No network adapter to restart') }
            else {
                try {
                    $ads | Restart-NetAdapter -Confirm:$false -ErrorAction Stop
                    SetStatus (T 'Waiting for the connection to come back') 80
                    for ($i = 0; $i -lt 20; $i++) {
                        Start-Sleep -Seconds 1
                        if (@(Get-NetIPConfiguration -ErrorAction SilentlyContinue | Where-Object { $_.IPv4DefaultGateway }).Count) { break }
                    }
                    Step 'fix.adapter' 'ok' (T 'Restarted')
                } catch {
                    Log $_.Exception.Message 'warn'
                    Step 'fix.adapter' 'warn' $_.Exception.Message
                }
            }
            [pscustomobject]@{ Done = $true }
        }
    }
}

$NetSteps = @(
    @('net.adapter', 'Network connection'),
    @('net.ip', 'IP address'),
    @('net.router', 'Router'),
    @('net.internet', 'Internet'),
    @('net.dns', 'Name lookup (DNS)'),
    @('net.web', 'Websites')
)

function Start-NetDiagnosis([switch]$AfterFix) {
    if (-not $AfterFix) { $script:NetFixTried = $false }
    $script:Ctx = @{}
    Open-TaskPage (T 'Checking your internet connection') (T 'This takes up to a minute. Nothing is changed.') 'Home'
    foreach ($s in $NetSteps) { Add-TaskStep $s[0] (T $s[1]) }
    Start-Flow @({
        Start-TaskWork -Work { Invoke-NetDiagnosis } -OnDone { param($r, $err) Complete-NetDiagnosis $r $err }
    })
}

function Complete-NetDiagnosis($r, $err) {
    if ($err -or -not $r) {
        if ($err) { Add-TaskLog "[X] $err" }
        Complete-Task -ForceState error -ForceTitle (T "Couldn't finish the check") -ForceMessage "$err"
        return
    }
    $msg = $r.Verdict
    if ($r.Note) { $msg = "$msg`n$($r.Note)" }
    if ($r.Portal) {
        $script:Ctx.Action = @{ Label = (T 'Open sign-in page'); Run = { Start-Process 'http://www.msftconnecttest.com/redirect' } }
        Complete-Task -ForceState warn -ForceTitle (T 'You need to sign in to this network') -ForceMessage $msg
        return
    }
    if (-not $r.Failed) {
        Complete-Task -ForceState ok -ForceTitle (T 'Your internet connection works') -ForceMessage $msg
        return
    }
    if ($script:NetFixTried) {
        $msg += "`n" + (T "The quick fix didn't solve it. Try restarting the router, or open network settings for more troubleshooting.")
        $script:Ctx.Action = @{ Label = (T 'Open network settings'); Run = { Start-Process 'ms-settings:network-status' } }
    } else {
        $script:Ctx.Action = @{ Label = (T 'Try a quick fix'); Run = { Start-NetFix } }
    }
    Complete-Task -ForceState error -ForceTitle (T 'Found a problem') -ForceMessage $msg
}

function Start-NetFix {
    $admin = Test-IsAdmin
    if (-not $admin) {
        $d = Show-Dialog -Title (T 'Run as administrator for the full fix?') -Icon shield `
            -Message (T 'Getting a new address and restarting the network adapter need administrator rights. Without them, only the name lookup cache is cleared.') `
            -Buttons 'Run as administrator', 'Continue anyway', 'Cancel'
        if ($d.Button -eq 'Run as administrator') { Restart-AsAdmin; return }
        if ($d.Button -ne 'Continue anyway') { return }
    }
    $script:NetFixTried = $true
    $script:Ctx = @{ NoHistory = $true }
    Open-TaskPage (T 'Trying a quick fix') (T 'Your connection may drop for a few seconds.') 'Home'
    Add-TaskStep 'fix.dns' (T 'Clear the name lookup cache')
    Add-TaskStep 'fix.ip' (T 'Ask the router for a new address')
    Add-TaskStep 'fix.adapter' (T 'Restart the network adapter')
    Start-Flow @(
        {
            Start-TaskWork -ArgumentList (Test-IsAdmin) -Work { param($admin) Invoke-NetFix $admin } -OnDone {
                param($r, $err)
                if ($err) { Add-TaskLog "[X] $err" }
                Add-History -Title (T 'Quick fix for internet') -State ok -Detail (T 'Cleared the name lookup cache, renewed the address and restarted the network adapter where possible.')
                Invoke-NextStage
            }
        },
        { Start-NetDiagnosis -AfterFix }
    )
}
